/*
 * proto.h - prototypes for the "compexp" (expanded) compiler.
 *
 * cj.h has #included "proto.h" since the first commit, but the file itself was
 * never in the tree, so compexp/compx never built.  These prototypes are
 * generated from compexp's own (preprocessor-active) function definitions:
 * ANSI-style definitions get an exact prototype, K&R-style definitions get an
 * empty parameter list (compatible with the K&R default argument promotions).
 * This fixes the call-before-definition conflicts, lets functions be used as
 * function pointers, and silences the cross-file implicit-declaration warnings.
 *
 * The fully ANSI-prototyped variant lives in compexpansi, whose signatures do
 * NOT match compexp's, so its proto.h cannot be used here.  main() and the
 * functions already declared in cj.h's extern block are intentionally omitted.
 */

